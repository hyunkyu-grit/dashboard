def for_event(label: str) -> list[dict]:
    """라벨에 걸리는 «설명 + 방향» 한 벌씩. `EVENT` 와 같은 순서로.

    **둘을 따로 내지 않는다.** 따로 내면 화면이 설명 문단과 방향 문단을 각각
    그리고, 둘이 같은 사실을 말하므로 같은 문단이 두 번 찍힌다(실측 2026-08-21).

    라벨 하나가 두 열쇠말에 걸릴 수 있다(«국고채 물가 비경쟁인수» 는 둘이다).
    합치지 않고 다 낸다 — 합치려면 가중치를 지어내야 하는데 근거가 없다.
    """
    return [
        {"key": key, "text": text, "dir": EVENT_BIAS.get(key)}
        for key, text in EVENT
        if key in (label or "")
    ]


def net_dir(dirs: list[str]) -> str:
    """여러 방향을 칸 하나의 방향으로. **한쪽으로 모일 때만 방향이 있다.**

    달력 칸은 그날 전부를 한 글자로 눌러야 한다. 흡수와 공급이 같은 날 나오면
    (화요일 RP매입 · 목요일 RP매각은 요일 패턴이지만 겹치는 날이 있다) 순액을
    셀 수가 없다 — 금액의 방향 효과가 서로 다른 시장에 닿기 때문이다. 그래서
    갈리면 «양방향» 이라고 말하고, 자세한 것은 눌러서 보게 한다.
    """
    real = {d for d in dirs if d in (BULL, BEAR)}
    if len(real) == 1:
        return real.pop()
    if len(real) > 1:
        return BOTH
    return BOTH if BOTH in dirs else FLAT


def for_lane(lane: str) -> dict | None:
    return LANE.get(lane)


def for_label(label: str) -> list[str]:
    """라벨에 걸리는 덧붙임 설명들. 없으면 빈 목록."""
    return [txt for key, txt in EVENT if key in (label or "")]


def explain(lane: str, label: str = "") -> dict:
    """상세 화면이 그대로 출력할 설명 묶음 — 이제 방향까지 같이 나른다."""
    base = LANE.get(lane) or {}
    return {
        "title": base.get("title"),
        "what": base.get("what"),
        "why": base.get("why"),
        "note": base.get("note"),
        "extra": for_label(label),
        "bias": LANE_BIAS.get(lane),
        # 방향을 적는 자리마다 이 한 줄이 따라간다 — 없으면 «인상인데 왜
        # 금리가 내렸지» 가 화면의 결함으로 보인다.
        "biasCaveat": BIAS_CAVEAT if lane in LANE_BIAS else None,
    }
