#: 어미 규칙. **순서가 규칙의 일부다** — 좁은 것이 먼저다.
#: `않습니다` 는 `않어요` 가 아니라 `않아요` 라서 일반 규칙보다 앞에 선다.
_ENDINGS: list[tuple[str, str]] = [
    ("않습니다", "않아요"),
    ("줍니다", "줘요"),
    # 여기 남는 «습니다» 는 전부 과거형(았/었/였/왔/뒀/됐) 뒤다 — 실측으로
    # 확인했고, `test_the_payload_speaks_one_register` 가 남는 것을 잡는다.
    ("습니다", "어요"),
]


def _has_final(ch: str) -> bool:
    """한글 음절에 받침이 있나. 눈으로 고르면 «업무이에요» 가 남는다."""
    code = ord(ch) - 0xAC00
    return 0 <= code <= 11171 and code % 28 != 0


def to_haeyo(text: str) -> str:
    """합니다체 한 문장을 해요체로. 사실은 한 글자도 안 건드린다.

    «입니다» 는 앞 음절의 받침이 «이에요/예요» 를 가른다. 산수라 눈으로 고를
    일이 아니다.
    """
    out = text
    while "입니다" in out:
        i = out.index("입니다")
        stem = out[:i]
        tail = out[i + 3:]
        joiner = "이에요" if stem and _has_final(stem[-1]) else "예요"
        out = stem + joiner + tail
    for old, new in _ENDINGS:
        out = out.replace(old, new)
    return out


def speak(value):
    """중첩된 페이로드 조각의 모든 문자열을 해요체로. 다른 값은 그대로 둔다."""
    if isinstance(value, str):
        return to_haeyo(value)
    if isinstance(value, dict):
        return {k: speak(v) for k, v in value.items()}
    if isinstance(value, list):
        return [speak(v) for v in value]
    return value


