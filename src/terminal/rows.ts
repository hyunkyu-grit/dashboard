/**
 * THE 터미널 행 높이들. 앱 캐논의 `ROW_H = 60` 과 **다른 수**이고, 다른 이유가
 * 있어서 다르다.
 *
 * 60 은 두 줄 이름 칸(종목 + 테너/커브 위치)이 CDS `condensed` 패딩 안에 앉는
 * 높이다. 이 화면의 행은 **한 줄**이고, 요구가 «수백 줄이 쌓이는 로그» 라서
 * 60 이면 20% 폭 칸에 스무 줄이 못 선다.
 *
 * ── 두 수를 **팔란티어에서 재 왔다** [OWNER 2026-08-26] ─────────────────────
 * 「고밀도」를 짐작으로 정하지 않기 위해 Blueprint 의 스프레드시트 Table 을
 * 브라우저에서 직접 쟀다(blueprintjs.com/docs/#table, 다크):
 *
 *     셀 높이      20px
 *     셀 패딩      0 8px
 *     셀 타이포    12px / line-height 20 / w400
 *
 * `TERM_LOG_H` 가 그 20 이다. 좌측 자산 행만 24 인 이유는 그 칸의 라벨이
 * **한글**이라서다 — 20px 행에 12px 한글을 넣으면 글자 위아래에 1px 씩만
 * 남아서, 받침이 있는 음절이 행 경계에 닿는다. 24 는 Foundry Quiver 좌측
 * 트리 행의 밀도이기도 하다(같은 화면에서 실측).
 *
 * 캐논이 «한 수로 선언한다» 고 말하는 규칙은 그대로 지킨다 — 가상 스크롤의
 * 스페이서 산술이 이 값을 읽으므로, 행이 이 높이가 아니면 스크롤바가
 * 거짓말을 한다.
 */

/** 좌측 자산 행. 한글 라벨이 서는 높이 — 위 주석. */
export const TERM_ROW_H = 24;

/** 우측 로그 행. Blueprint 스프레드시트 셀 실측값. */
export const TERM_LOG_H = 20;

/** 패널 머리. 스크롤되는 창에 안 들어간다. */
export const TERM_HEAD_H = 32;

/** 로그 표의 열 머리. 패널 머리보다 한 단 낮다 — 표 안의 것이지 패널의 것이
 *  아니라는 표시이고, 두 머리가 같은 높이로 겹쳐 서면 어느 쪽이 상위인지가
 *  안 읽힌다. */
export const TERM_LOG_HEAD_H = 24;

/** 보이는 창 밖으로 더 그리는 행 수. 캐논(`table/rowHeight.ts`)의 8 과 같은
 *  값을 쓴다 — 행이 절반 높이라 같은 픽셀을 덮으려면 더 필요할 것 같지만,
 *  빠른 스크롤에서 빈칸이 보이는지는 픽셀이 아니라 프레임의 문제라 같다. */
export const TERM_OVERSCAN = 8;
