/* 52주 트랙 위에서 **지금이 어디인가** — 한 곳에서만 답한다.
 *
 * v1 패리티 레인 P0-3 (LANE-v1-parity-2026-08-20.md).
 *
 * ## 이 파일이 생긴 이유
 *
 * 표의 위치 트랙이 **순위 백분위**를 그리고 있었다. 백엔드의
 * `range1y.pct` 는 `bisect_left(sorted, now) / len` 이다 — "지난 1년 중
 * 오늘보다 낮았던 날의 비율". 그런데 화면은 그 값을 최저↔최고 트랙 위의
 * `left: {pct}%` 로 놓았고, 옆에는 최저·최고·평균이 인쇄돼 있었다. 읽는 사람은
 * 마커를 그 두 끝 사이의 자리로 읽는다. 툴팁도 "레인지의 X% 지점" 이라고
 * 그렇게 말했다.
 *
 * 두 양은 다르다. 라이브 실측 2026-08-20, 99행:
 *
 *     6M-1Y-2Y   현재 2.500  저 −17.000  고 14.750   순위 85.3%  선형 61.4%
 *     3Y-5Y      현재 13.250 저 4.750    고 16.500   순위 88.1%  선형 72.3%
 *
 *     10%p 넘게 어긋난 행 20개, 최대 23.9%p
 *
 * 첫 줄이 이 병의 얼굴이다: 마커는 85% 에 서서 "고점에 거의 붙었다" 고 말하는데,
 * 옆의 숫자로 재면 61% 다. 그림과 숫자가 다른 말을 하고 있었다.
 *
 * [OWNER, 2026-08-20] 마커는 **선형 위치**다. 순위 백분위는 화면의 자리를
 * 잃지만 사라지지는 않는다 — 스크리너의 고점권/저점권 칩이 그것을 쓰고, 그건
 * 순위로 말하는 것이 옳은 자리다("상위 10%").
 *
 * ## 왜 프런트에서 계산하나
 *
 * `ROW_FIELD_SOURCE`(§16)는 프런트가 시장 데이터에 산술을 하지 못하게 한다.
 * 이 값은 그 규칙의 예외가 아니라 **적용 대상이 아니다**: 행이 실어 나르는
 * 숫자가 아니라 **그리는 좌표**다. 화면에 인쇄되는 세 숫자에서 나오고, 그
 * 셋과 어긋날 수 없다는 것이 그 성질의 전부다. `ForwardMatrix` 의 게이지가
 * 처음부터 이렇게 하고 있었다 — 이 파일은 그 산술을 옮겨 담아 **두 트랙이
 * 다시 갈리지 못하게** 한다.
 */

/** 최저↔최고 위에서 `now` 의 자리, 0~100. 그릴 수 없으면 null.
 *
 * 범위 밖이면 끝으로 클램프한다 — 트랙을 벗어난 마커는 자리를 말하는 대신
 * 레이아웃을 깨뜨린다. 클램프가 일어났다는 사실 자체는 드문 일이고(현재가
 * 52주 창 안에 있는 것이 정의상 보통이다), 일어나면 끝에 붙는 것이 맞다.
 *
 * `max === min` 은 자리라는 개념이 없는 상태다(1년 내내 같은 값). 0 으로
 * 그리면 "바닥에 있다" 는 없는 사실을 말하게 되므로 null 을 낸다. */
export function rangePosition(
  now: number | null | undefined,
  min: number | null | undefined,
  max: number | null | undefined,
): number | null {
  if (now == null || min == null || max == null) return null;
  if (!Number.isFinite(now) || !Number.isFinite(min) || !Number.isFinite(max)) return null;
  if (max <= min) return null;
  return Math.max(0, Math.min(100, ((now - min) / (max - min)) * 100));
}
