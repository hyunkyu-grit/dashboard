/**
 * 컨트롤 행의 **기본** 높이. 한 수, 한 번 고침, 한 가지 눈에 보이는 변화.
 *
 * `table/rowHeight.ts::ROW_H` 와 같은 자리다 — 저기가 표의 행, 여기가 컨트롤의
 * 행이다.
 *
 * ── «유일한» 높이는 아니다 [실측 2026-08-19, `guards/control-parity`] ────────
 * 등고는 앱 전역 상수가 아니라 **그 행의 성질**이다. Setting 의 조달 스프레드
 * 칸을 32 로 내렸더니 오히려 나빠졌는데, 그 칸의 이웃이 Select 가 아니라
 * `SegmentedTabs`(36)여서 32 는 중심선을 2px 벌리고 **36 만이 0** 이었다.
 * 그래서 허용 집합은 `{32, 36}` 이고 그 판정은 `control-parity` 가 진다.
 * 이 상수는 그중 **기본값** — 어느 값을 고르는지는 행이 정하고, 고른 이유는
 * 호출부 주석이 적는다.
 *
 * ── 왜 상수가 필요했나 [실측 2026-08-27] ────────────────────────────────────
 * CLAUDE.md 「얼라인」 1 은 «컨트롤 행 등고 32px» 을 2026-08-25 부터 못 박고
 * 있었다. 그런데 그 32 는 **일곱 파일에 열세 번 따로 적혀** 있었고, 그래서
 * 규칙을 어긴 자리를 아무것도 잡아 주지 못했다:
 *
 *     CDS `Select` 의 `size="s"` 기본 트리거는 **30px** 이다. 캐논은 32라고
 *     적혀 있는데 그 둘을 잇는 것이 없어서, 백테스트 설정 줄의 Select 두 칸만
 *     30@153 으로 앉고 나머지 넷은 32@151 이었다. 바닥 정렬 행에서는 블록
 *     높이가 곧 라벨 높이라(「얼라인」 3) 라벨 줄까지 135 대 133 으로 갈렸다.
 *
 * 수를 한 곳에 모으면 그 사고가 **다음에는 타입 검사에 걸린다** — 새 컨트롤이
 * 이 상수를 안 지고 들어오는 것을 `guards/align-canon.test.ts` 가 잡는다.
 *
 * ── 값이 32 인 이유 ────────────────────────────────────────────────────────
 * CDS `TextInput` 의 `size="s"` 자연 높이가 30 이고 `Select` 도 같다. 32 는
 * 그보다 한 칸 큰 수인데, 이 리포가 그것을 고른 것은 **알약 버튼**(`.sr-pillbtn`
 * — 14/600 글자에 상하 8px 패딩) 때문이다. 그 셋이 한 행에 서는 화면이라
 * (백테스트 설정 줄·전략 실험 창) 가장 큰 것에 맞췄다.
 *
 * ── 이 수를 쓰는 곳 셋 ─────────────────────────────────────────────────────
 *   1. 컨트롤 자체 — `TextInput height` · `DateInput height` ·
 *      `DROPDOWN_STYLES.control.height`
 *   2. 컨트롤이 아닌 **값**의 상자 — `<VStack height={CONTROL_H}>`
 *      (백테스트 「진입 레벨」·시뮬 시작일/마감일 판례: 맨살 글자면 그 칸만
 *      라벨이 내려앉는다)
 *   3. 컨트롤이 든 행 자체 — `<HStack height={CONTROL_H}>`
 *
 * **이것이 오너의 다이얼이다.** 이 수를 바꾸면 컨트롤 행의 밀도가 바뀌고,
 * 다른 것은 움직일 필요가 없다.
 */
export const CONTROL_H = 32;
