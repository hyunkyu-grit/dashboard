/* THE stacking order. 떠 있는 것은 전부 여기서 자기 층을 고른다.
 *
 * v1 이 이 파일을 만든 이유가 실측이다 [OWNER, 2026-07-31 — "밑에 팝업이 이거
 * 때문에 가려지는데"]: 하단 스트립이 크롬(z-40)이고 백테스트 시트가 모달(z-30)
 * 이라 숫자가 제품의 뜻과 반대로 적혀 있었다. 스타일 실수가 아니라 **층을 각자
 * 정한 결과**다 — 다섯 파일에서 따로 고르면 둘이 한 화면에 뜨기 전까지 충돌이
 * 안 보인다.
 *
 * 규칙 한 문장: **모달은 언제나 크롬 위에.** 모달은 화면을 덮고 조작을 가져간다.
 * 그 위에 계속 그려지는 것은 덮인 채로 못 누르거나, 누를 수 있는데 눌리면 안
 * 되는 것 둘 중 하나다.
 *
 * v2 는 Tailwind 가 아니므로 **숫자**다(인라인 style / CSS 변수로 들어간다).
 * v1 의 값과 같은 자리를 유지한다.
 */

/** 표의 sticky 헤더 — 스크롤 컨테이너 **안쪽**이라 제일 아래. */
export const Z_TABLE_HEAD = 10;

/** 상단 내비(`.sr-nav`). CSS 에도 20 으로 적혀 있고 여기가 그 근거다. */
export const Z_NAV = 20;

/** 페이지 크롬 — 본문보다 오래 사는 것들(하단 스트립·커맨드바, 아직 없음). */
export const Z_CHROME = 40;

/** 떠 있는 창. 읽는 사람이 **자리를 정해 둔 병행 작업면**이라 크롬 위에 뜬다 —
 * 다만 모달 아래다. 창이 모달을 덮으면 덮이면 안 되는 것이 눌린다. */
export const Z_WINDOW = 45;

/** 모달 — 화면을 덮고 조작을 가져가는 것. 크롬 위이고 창 위다. */
export const Z_MODAL = 50;
