/* 창 안 드롭다운의 폭 — **가장 긴 항목만큼**.
 *
 * CDS `Select` 의 드롭다운은 기본적으로 컨트롤과 같은 폭이다. 값이 토큰일 때는
 * 맞는 기본값인데(`10Y`, `3Y-10Y`), 이 제품의 목록은 **문장**이다:
 *
 *   "스티프너 (10Y 페이 · 3Y 리시브)"   방향, 백테스트·시뮬 공용
 *   "3Y 페이 · 1Y/10Y 리시브"            플라이는 용어를 안 지어내고 다리를 적는다
 *   "아웃라이트" · "버터플라이"           종류
 *
 * 그 폭에 맞춰 컨트롤을 키우면 줄이 화면을 넘고, 안 키우면 항목이 두 줄로 접힌다
 * (실측 2026-08-14: 137px 드롭다운에서 "아웃라이트" 가 접혀 행 높이가 36 → 60).
 * 목록만 넓히는 것이 답이다 — 목록은 떠 있는 면이라 줄을 밀지 않는다.
 *
 * 상한을 두는 이유: `max-content` 는 상한이 없어서, 언젠가 긴 라벨 하나가 목록을
 * 화면 밖으로 밀어낸다. 340 은 위 문장 중 가장 긴 것이 한 줄로 들어가는 폭이다.
 *
 * ── 컨트롤 값의 13px [OWNER 2026-08-19 — "종목, 방향, 규모의 세팅값은 과하게
 * 큽니다"] ──────────────────────────────────────────────────────────────────
 * CDS 는 size="s" 여도 값 텍스트를 body(16px)로 찍는다. 이 창들의 나머지 —
 * 칸 라벨(caption 13), 날짜 입력(`.sr-date` 13), 진입 레벨 — 옆에서 16px 값만
 * 혼자 크다. 줄이는 자리는 **`font="legal"` prop** 이다(백테스트·현금채권 창의
 * Select 들): `styles.controlValueNode` 는 감싸는 DIV 에 인라인으로 앉아서 값
 * `<p>` 자신의 body 클래스에 진다(실측 2026-08-19 — 16px 그대로). 목록
 * (dropdown)은 그대로 둔다 — 떠 있는 면은 줄을 밀지 않아 클 수 있다. */
/**
 * ── 컨트롤은 **제 상자를 채운다** [OWNER 2026-08-25 — "간격이 띄엄띄엄이고 …
 *    전체적인 사이트에서의 «얼라인» 이 없다"] ────────────────────────────────
 *
 * 이 리포는 얼라인을 오래 **세로**로만 재고 있었다(등고 32·바닥 정렬). 그런데
 * 실제로 눈에 걸린 것은 **가로**였다. 백테스트 북 한 줄을 실측하면(2026-08-25)
 * 컨트롤 사이 빈틈이 **62 · 97 · 12 · 23px** 로 들쭉날쭉이다.
 *
 * 뿌리는 CDS `Select` 가 **제 상자를 안 채운다**는 것이다. 상자는 「말줄임 금지」
 * 때문에 최장 라벨 기준으로 잡아 뒀는데(종목 168 = 크롬 82 + «캐피탈채 AA-»),
 * 트리거는 **지금 값**만큼만 넓어진다(«1D» → 83). 남는 85px 이 죽은 폭이 되어
 * 옆 칸까지 밀어 놓는다:
 *
 *     종류   Box 140  트리거  90   죽은 폭 50
 *     종목   Box 168  트리거  83   죽은 폭 85   ← 여기가 «띄엄띄엄» 의 정체
 *     규모   Box  88  입력    88   죽은 폭  0   ← TextInput 은 원래 채운다
 *
 * `width: 100%` 를 트리거에 주면 죽은 폭이 사라지고, 남는 간격은 행이 준
 * `gap` **하나**가 된다 — 그게 「한 행에 서는 것들은 자로 잰 듯」의 가로 판이다.
 * 상자 폭 자체는 안 건드린다: 그 숫자들은 말줄임 금지의 실측값이라 그대로 둔다.
 *
 * 한 곳에 두는 이유는 이 상수가 이미 여덟 개 `Select` 전부에 걸려 있기
 * 때문이다(백테스트 3 · 시뮬 2 · rv 1 · 종목군·시작 필터 각 1). 전부 고정폭
 * `Box` 안에 살아서 100% 가 그 상자를 뜻한다 — `guards/control-fill.test.ts`
 * 가 새 `Select` 가 이 상수를 안 지고 들어오는 것을 막는다.
 */
export const DROPDOWN_STYLES = {
  root: { width: "100%" },
  control: { width: "100%" },
  dropdown: { width: "max-content", minWidth: 120, maxWidth: 340 },
} as const;
