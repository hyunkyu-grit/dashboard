/* 페이지 거터 — 모든 표면이 창 가장자리에서 떨어지는 거리.
 *
 * 사우론(swap-monitor)에서 그대로 가져왔다. 상수가 **하나**인 이유는 가장자리에
 * 닿는 표면이 한 요소가 아니기 때문이다: 헤더 띠, 좌측 조건 패널, 우측 미리보기,
 * 결과의 각 구획이 저마다 독립적으로 가장자리에 닿는다. 넷이 합의하고 다섯째가
 * 어긋나는 것은, 다섯째가 다른 넷 옆에 나타나기 전까지 아무도 눈치채지 못하는
 * 종류의 표류다.
 *
 * **Tailwind는 소스 텍스트를 읽는다.** 그래서 문자 그대로 `px-6`이어야 하고,
 * 숫자에서 조립한 템플릿이면 안 된다 — 런타임에 만들어진 클래스는 빌드 시점에
 * 생성된 적 없는 규칙을 가리키고, 여백은 조용히 사라진다.
 *
 * 80 → 24 [2026-08-07]. 모니터가 좌측 사이드바를 들이면서 같이 움직였다.
 * 시뮬레이션은 그 사이드바 **안쪽**의 한 탭이므로 창 가장자리까지의 거리는
 * 사이드바가 이미 만든다. 두 값이 갈리면 탭을 옮길 때마다 본문이 옆으로
 * 튄다 — 같은 창 안에서 거터가 둘일 이유가 없다. 근거는 ui/pageGutter.ts.
 */

/** 전폭 표면의 좌우 거터. 6 × 4px = 24px. */
export const PAGE_X = "px-6";

/** 왼쪽 가장자리에만. 2단 배치의 좌측 패널용 — 오른쪽은 내부 구분선이라
 * 보통 간격을 쓴다. */
export const PAGE_L = "pl-6";

/** 오른쪽 가장자리에만. 2단 배치의 우측 패널용. */
export const PAGE_R = "pr-6";

/** 클래스를 못 쓰는 계산용 (차트 폭은 패널의 콘텐츠 박스에서 나온다).
 * 위 상수들과 반드시 같이 움직인다. */
export const PAGE_X_PX = 24;
